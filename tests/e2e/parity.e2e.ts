test('reflow: only local final answers enter the shared store and removal re-enables the action', async ({ page }) => {
  await prepareSeedPage(page)
  const child = await openSideChat(page)
  const side = sideChatOf(page)
  const all = side.getByRole('button', { name: /^(Reflow all|整段回流)$/ })
  await expect(all).toBeDisabled()
  await expect(side.getByRole('button', { name: /^(Send back to main session|回流到主会话)$/ })).toHaveCount(0)
  await selectModel(page, side, 'Controlled E2E')
  const input = side.locator('[data-composer-input]')
  await input.fill('local reflow answer one'); await input.press('Enter')
  await expect(side.getByRole('button', { name: /^(Stop generating|停止生成)$/ })).toHaveCount(0)
  await expect(all).toBeEnabled()
  const single = side.getByRole('button', { name: /^(Send back to main session|回流到主会话)$/ })
  await expect(single).toHaveCount(1)
  await single.click()
  const records = () => page.evaluate(id => JSON.parse(localStorage.getItem('dsh-sidenote:reflow:v1:' + id) ?? '[]'), process.env.DSH_E2E_SEED_SESSION!)
  await expect.poll(records).toMatchObject([{ question: 'local reflow answer one', sourceKey: expect.stringContaining(child) }])
  await expect(side.getByRole('button', { name: /^(Reflowed ✓|已回流 ✓)$/ })).toBeDisabled()
  const main = page.locator('[data-conversation-session]').first()
  await main.getByRole('button', { name: /1 side-chat reflow|1 条侧边回流/ }).click()
  await main.getByRole('button', { name: /Remove reflow|移除回流/ }).click()
  await expect.poll(records).toHaveLength(0)
  await expect(single).toBeEnabled()
  const completedTurns = () => sessionEventsOf(child).filter(event => event.type === 'turn/end' && event.data.reason?.kind === 'completed').length
  const completed = completedTurns()
  await input.fill('local reflow answer two'); await input.press('Enter')
  // The previous reply keeps this action enabled until admission starts.
  // Wait for the new durable completion before clicking the whole-chat action.
  await expect.poll(completedTurns).toBe(completed + 1)
  await expect(side.getByRole('button', { name: /^(Stop generating|停止生成)$/ })).toHaveCount(0)
  await expect(single).toHaveCount(2)
  await expect(all).toBeEnabled(); await all.click()
  await expect.poll(records).toHaveLength(2)
})

test('busy: native queue is visible and saving cannot discard running or queued work', async ({ page }) => {
  await prepareSeedPage(page)
  const child = await openSideChat(page)
  const side = sideChatOf(page)
  await selectModel(page, side, 'Controlled E2E')
  const input = side.locator('[data-composer-input]')
  const save = side.getByRole('button', { name: /^(Save as session|保存为正式会话)$/ })
  await input.fill('save guard while running [e2e:hold]'); await input.press('Enter')
  await expect(side.getByRole('button', { name: /^(Stop generating|停止生成)$/ })).toBeVisible()
  await expect(save).toBeDisabled()
  await input.fill('visible queued message')
  await side.getByRole('button', { name: /^(Queue message|加入队列|排队发送)$/ }).click()
  await expect(side.getByText('visible queued message', { exact: true })).toBeVisible()
  await expect(input).toHaveText('')
  await side.getByRole('button', { name: /^(Stop generating|停止生成)$/ }).click()
  await expect(save).toBeDisabled()
  await expect.poll(() => sessionEventsOf(child).at(-1)?.type).toBe('turn/end')
  await expect(page.getByRole('alert').filter({ hasText: /finished replying|回复完成/ })).toHaveCount(0)
  expect(userMessagesOf(child).some(text => text.includes('visible queued message'))).toBe(false)
  await input.fill('resume queued work'); await input.press('Enter')
  await expect.poll(() => userMessagesOf(child).some(text => text.includes('visible queued message'))).toBe(true)
  await expect(save).toBeEnabled()
  await expect(page.getByRole('alert').filter({ hasText: /finished replying|回复完成/ })).toBeVisible()
})

test('commands: native slash completion and file references work inside the child', async ({ page }) => {
  writeFileSync(join(process.env.DSH_E2E_WORKSPACE!, 'README.md'), 'Native reference fixture\n')
  await prepareSeedPage(page)
  const child = await openSideChat(page)
  const side = sideChatOf(page)
  const input = side.locator('[data-composer-input]')
  await input.fill('/go')
  await page.getByRole('option', { name: /^goal\b/i }).click()
  await expect(input).not.toHaveText('/go')
  await input.press('Escape'); await input.fill('')
  await input.pressSequentially('@README')
  await page.getByRole('option', { name: /README\.md/ }).first().click()
  await expect(input).toContainText('README.md')
  await input.press('Enter')
  await expect.poll(() => userMessagesOf(child).some(text => text.includes('README.md'))).toBe(true)
})

test('files: the native side composer accepts a non-image attachment and preserves its recipient', async ({ page }) => {
  await prepareSeedPage(page)
  const child = await openSideChat(page)
  const side = sideChatOf(page)
  await selectModel(page, side, 'Controlled E2E')
  await side.locator('input[type=file]').setInputFiles({ name: 'brief.txt', mimeType: 'text/plain', buffer: Buffer.from('Native generic attachment\n') })
  await expect(side.locator('[data-composer-seat]')).toContainText('brief.txt')
  const input = side.locator('[data-composer-input]')
  await input.fill('generic attachment delivery')
  await side.getByRole('button', { name: /^(Send message|发送消息)$/ }).click()
  await expect.poll(() => userMessagesOf(child).some(text => text.includes('generic attachment delivery'))).toBe(true)
  expect(JSON.stringify(userMessageContentsOf(child).at(-1))).toContain('brief.txt')
  expect(userMessagesOf(process.env.DSH_E2E_SEED_SESSION!).some(text => text.includes('generic attachment delivery'))).toBe(false)
})

test('appearance: native typography, dark theme and Chinese controls remain aligned in a narrow pane', async ({ page }) => {
  await prepareSeedPage(page)
  await openSideChat(page)
  const side = sideChatOf(page)
  const compare = async () => {
    const styles = await page.locator('[data-composer-input]').evaluateAll(inputs => inputs.map(input => {
      const style = getComputedStyle(input)
      return { font: style.fontFamily, size: style.fontSize, line: style.lineHeight, color: style.color }
    }))
    expect(styles).toHaveLength(2)
    expect(styles[1]).toEqual(styles[0])
  }
  await compare()
  const body = page.locator('body')
  const settings = page.getByRole('dialog', { name: /^(Settings|设置)$/ })
  try {
    await openGeneralSettings(page)
    await settings.getByRole('button', { name: /^(Dark|深色)$/ }).click()
    await settings.getByRole('button', { name: /^(English|中文)$/ }).click()
    await page.getByRole('menuitem', { name: '中文', exact: true }).click()
    await settings.getByRole('button', { name: /^(Close(?: settings)?|关闭(?:设置)?)$/i }).click()
    await page.setViewportSize({ width: 1000, height: 800 })
    await expect(body).toHaveAttribute('data-ds-dark-theme', '')
    await expect(body).toHaveCSS('background-color', 'rgb(21, 21, 23)')
    await expect(side.getByRole('button', { name: '保存为正式会话', exact: true })).toBeVisible()
    await compare()
    expect(await side.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    await page.screenshot({ path: 'test-results/native-dark-chinese.png' })
  } finally {
    await page.setViewportSize({ width: 1280, height: 800 })
    if (!await settings.isVisible()) await openGeneralSettings(page)
    await settings.getByRole('button', { name: /^(English|中文)$/ }).click()
    await page.getByRole('menuitem', { name: 'English', exact: true }).click()
    await settings.getByRole('button', { name: /^(Light|浅色)$/ }).click()
    await settings.getByRole('button', { name: /^(Close(?: settings)?|关闭(?:设置)?)$/i }).click()
    await expect(body).not.toHaveAttribute('data-ds-dark-theme', '')
    await expect(body).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(side.getByRole('button', { name: 'Save as session', exact: true })).toBeVisible()
    // Reload must read the saved host preferences; the optimistic UI alone
    // cannot prove that the next test will start in English and light mode.
    await page.reload()
    await expect(body).not.toHaveAttribute('data-ds-dark-theme', '')
    await expect(body).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(side.getByRole('button', { name: 'Save as session', exact: true })).toBeVisible()
  }
})
