test('draft: refresh and closed-chat recovery retain the native draft in the same child', async ({ page }) => {
  await prepareSeedPage(page)
  const child = await openSideChat(page)
  const side = sideChatOf(page)
  const input = side.locator('[data-composer-input]')
  await input.fill('persistent side draft')
  await page.reload(); await prepareSeedPage(page)
  await expect(side).toHaveAttribute('data-sidenote-chat-session', child)
  await expect(input).toHaveText('persistent side draft')
  await page.getByRole('tab', { name: /^Side.*Close$/ }).getByRole('button', { name: 'Close', exact: true }).click()
  await expect(side).toHaveCount(0)
  const mainInput = page.locator('[data-composer-input]').first()
  await mainInput.fill('/side')
  await page.getByRole('option', { name: /^side /i }).click()
  await page.getByRole('option', { name: /^Reopen|^重开/ }).first().click()
  await expect(side).toHaveAttribute('data-sidenote-chat-session', child)
  await expect(input).toHaveText('persistent side draft')
  await input.fill(Array.from({ length: 8 }, (_, i) => 'line ' + i).join('\n'))
  expect((await input.boundingBox())!.height).toBeGreaterThan(80)
  await input.press('Alt+s')
  await expect(mainInput).toBeFocused()
  await mainInput.press('Alt+s')
  await expect(input).toBeFocused()
})

